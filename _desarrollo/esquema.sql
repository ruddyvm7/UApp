-- UApp · Esquema completo de la base de datos de Supabase (proyecto uapp-produccion)
-- Foto de la estructura en producción al 1 de noviembre de 2026, ya con los ajustes de seguridad de la v2.8.2
-- (seguridad-v282.sql ejecutado ese día; la exportación de producción y la de las pruebas dan el mismo texto).
-- Solo estructura: tablas, llaves, índices, funciones, disparadores, políticas (RLS), permisos, el depósito de
-- archivos, la tarea diaria y el disparador de eventos. No trae ningún dato (ni avisos, ni consultas, ni editores).
--
-- Para qué sirve: ver de un vistazo qué hay en la base, revisar cada cambio en GitHub y poder recrearla desde cero
-- en un proyecto nuevo de Supabase (se ejecuta completo en el editor SQL; volver a ejecutarlo no borra nada).
-- Las pruebas automáticas (_desarrollo/pruebas/sql/) lo cargan en un PostgreSQL vacío y revisan permisos y topes.
--
-- Cómo se actualiza: ejecutar _desarrollo/exportar-esquema.sql en el editor SQL (solo lee) y reemplazar desde
-- «Secuencias» hacia abajo con lo que devuelve. Los cambios pendientes de ejecutar van en archivos aparte
-- (por ejemplo seguridad-v282.sql) hasta que se aplican en producción y se vuelve a exportar.
--
-- Requisitos al recrear: Supabase ya trae los esquemas auth, storage y cron (pg_cron activado en Database ›
-- Extensions). El disparador de eventos del final necesita los permisos del usuario postgres.

