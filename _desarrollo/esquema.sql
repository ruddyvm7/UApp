CREATE OR REPLACE FUNCTION public.consultas_limite()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare recientes int;
begin
  select count(*) into recientes from public.consultas
   where created_at > now() - interval '60 seconds';
  if recientes >= 60 then raise exception 'limite de consultas por minuto'; end if;
  if exists (select 1 from public.consultas
              where pregunta = new.pregunta
                and created_at > now() - interval '10 seconds') then
     raise exception 'consulta duplicada';
  end if;
  return new;
end; $function$;

