-- UApp · Exporta el esquema de la base (solo lee; no cambia nada)
-- Se ejecuta en el editor SQL de Supabase y devuelve una sola celda con el texto que va en _desarrollo/esquema.sql,
-- desde «Secuencias» hacia abajo: tablas, llaves, índices, funciones, disparadores, políticas, permisos, depósito,
-- tareas de pg_cron y el disparador de eventos. No lee ningún dato de las tablas.
-- La celda es larga: en el editor, usar «Copy cell content» o descargar el resultado como CSV.
-- Todo sale ordenado por nombre (orden «C», igual en cualquier base), así un cambio se ve como una línea en GitHub.

select ((
with
tablas as (
  select c.oid, c.relname, c.relrowsecurity, c.relacl
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'r'
),
cols as (
  select t.relname, string_agg(
           format('  %I %s', a.attname, format_type(a.atttypid, a.atttypmod))
           || case when a.attidentity = 'a' then ' generated always as identity'
                   when a.attidentity = 'd' then ' generated by default as identity' else '' end
           || case when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end
           || case when a.attnotnull then ' not null' else '' end,
           E',\n' order by a.attnum) as defs
  from tablas t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
  group by t.relname
),
cons as (
  select t.relname, string_agg(format('  constraint %I %s', co.conname, pg_get_constraintdef(co.oid)), E',\n'
           order by case co.contype when 'p' then 0 when 'u' then 1 when 'c' then 2 else 3 end, co.conname) as defs
  from tablas t join pg_constraint co on co.conrelid = t.oid and co.contype <> 'f'
  group by t.relname
),
s_fk as (
  select string_agg(format(E'do $$ begin\n  if not exists (select 1 from pg_constraint where conname = %L and conrelid = %L::regclass) then\n    alter table public.%I add constraint %I %s;\n  end if;\nend $$;', co.conname, 'public.' || quote_ident(t.relname), t.relname, co.conname, pg_get_constraintdef(co.oid)), E'\n' order by t.relname, co.conname) as txt
  from tablas t join pg_constraint co on co.conrelid = t.oid and co.contype = 'f'
),
s_seq as (
  select string_agg(format('create sequence if not exists public.%I;', c.relname), E'\n' order by c.relname) as txt
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')
),
s_tablas as (
  select string_agg(format(E'create table if not exists public.%I (\n%s%s\n);', t.relname, c.defs, coalesce(E',\n' || k.defs, ''))
           || case when t.relrowsecurity then format(E'\nalter table public.%I enable row level security;', t.relname) else '' end,
         E'\n\n' order by t.relname) as txt
  from tablas t join cols c using (relname) left join cons k using (relname)
),
s_indices as (
  select string_agg(replace(pg_get_indexdef(i.indexrelid), 'CREATE INDEX', 'create index if not exists') || ';', E'\n' order by i.indexrelid::regclass::text collate "C") as txt
  from pg_index i join tablas t on t.oid = i.indrelid
  where not exists (select 1 from pg_constraint co where co.conindid = i.indexrelid)
),
funcs as (
  select p.oid, p.proname, pg_get_function_identity_arguments(p.oid) as args, p.proacl, p.proowner
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f'
),
s_funcs as (
  -- las funciones creadas pegando texto desde Windows guardan saltos de línea \r\n: se dejan como \n (no cambia nada)
  select string_agg(rtrim(replace(pg_get_functiondef(f.oid), E'\r', ''), E'\n') || ';', E'\n\n' order by f.proname) as txt from funcs f
),
s_trig as (
  select string_agg(format('drop trigger if exists %I on %s;', tg.tgname, tg.tgrelid::regclass) || E'\n' || pg_get_triggerdef(tg.oid) || ';', E'\n' order by tg.tgrelid::regclass::text collate "C", tg.tgname) as txt
  from pg_trigger tg join tablas t on t.oid = tg.tgrelid where not tg.tgisinternal
),
s_pol as (
  select string_agg(format('drop policy if exists %I on %I.%I;', policyname, schemaname, tablename) || E'\n' ||
         format('create policy %I on %I.%I as %s for %s to %s', policyname, schemaname, tablename, lower(permissive), lower(cmd), array_to_string(roles, ', '))
         || coalesce(E'\n  using (' || qual || ')', '') || coalesce(E'\n  with check (' || with_check || ')', '') || ';',
         E'\n' order by tablename, policyname) as txt
  from pg_policies where schemaname = 'public'
),
g_tablas as (
  select t.relname, a.grantee::regrole::text as rol, string_agg(lower(a.privilege_type), ', ' order by a.privilege_type collate "C") as privs
  from tablas t cross join lateral aclexplode(t.relacl) a
  where a.grantee <> 0 and a.grantee::regrole::text in ('anon', 'authenticated', 'service_role')
  group by t.relname, a.grantee
),
s_gtab as (
  select string_agg(x, E'\n' order by o, x collate "C") as txt from (
    select 0 as o, format('revoke all on table public.%I from anon, authenticated;', relname) as x from tablas
    union all
    select 1, format('grant %s on table public.%I to %s;', privs, relname, rol) from g_tablas where rol <> 'service_role'
  ) q
),
s_gseq as (
  select string_agg(x, E'\n' order by o, x collate "C") as txt from (
    select 0 as o, format('revoke all on sequence public.%I from anon, authenticated;', c.relname) as x
    from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind = 'S'
    union all
    select 1, format('grant %s on sequence public.%I to %s;', string_agg(lower(a.privilege_type), ', ' order by a.privilege_type collate "C"), c.relname, a.grantee::regrole::text)
    from pg_class c join pg_namespace n on n.oid = c.relnamespace cross join lateral aclexplode(c.relacl) a
    where n.nspname = 'public' and c.relkind = 'S' and a.grantee <> 0 and a.grantee::regrole::text in ('anon', 'authenticated')
    group by c.relname, a.grantee
  ) q
),
s_gfun as (
  select string_agg(x, E'\n' order by o, x collate "C") as txt from (
    select 0 as o, format('revoke all on function public.%I(%s) from public, anon, authenticated;', proname, args) as x from funcs
    union all
    select 1, format('grant execute on function public.%I(%s) to %s;', f.proname, f.args, a.grantee::regrole::text)
    from funcs f cross join lateral aclexplode(coalesce(f.proacl, acldefault('f', f.proowner))) a
    where a.grantee <> 0 and a.grantee <> f.proowner and a.grantee::regrole::text in ('anon', 'authenticated')
    union all
    select 1, format('grant execute on function public.%I(%s) to public;', f.proname, f.args)
    from funcs f cross join lateral aclexplode(coalesce(f.proacl, acldefault('f', f.proowner))) a
    where a.grantee = 0
  ) q
),
-- permisos que reciben las tablas, secuencias y funciones que se creen después desde el editor SQL
-- (las crea el mismo usuario que ejecuta esto); los de supabase_admin solo los cambia Supabase
tipos_def(tipo, nombre) as (values ('r', 'tables'), ('S', 'sequences'), ('f', 'functions')),
s_gdef as (
  select string_agg(x, E'\n' order by o, x collate "C") as txt from (
    select 0 as o, format('alter default privileges for role %I in schema public revoke all on %s from anon, authenticated;', pg_get_userbyid(d.defaclrole), t.nombre) as x
    from pg_default_acl d join tipos_def t on t.tipo = d.defaclobjtype::text
    where d.defaclnamespace = 'public'::regnamespace and pg_get_userbyid(d.defaclrole) = current_user
    union all
    select 1, format('alter default privileges for role %I in schema public grant %s on %s to %s;', pg_get_userbyid(d.defaclrole), string_agg(lower(a.privilege_type), ', ' order by a.privilege_type collate "C"), t.nombre, a.grantee::regrole::text)
    from pg_default_acl d join tipos_def t on t.tipo = d.defaclobjtype::text cross join lateral aclexplode(d.defaclacl) a
    where d.defaclnamespace = 'public'::regnamespace and pg_get_userbyid(d.defaclrole) = current_user
      and a.grantee <> 0 and a.grantee::regrole::text in ('anon', 'authenticated')
    group by d.defaclrole, t.nombre, a.grantee
  ) q
)
select concat_ws(E'\n\n',
  E'-- ══ Secuencias ══\n' || coalesce((select txt from s_seq), '-- (ninguna)'),
  E'-- ══ Tablas ══\n' || (select txt from s_tablas),
  E'-- ══ Llaves foráneas ══\n' || coalesce((select txt from s_fk), '-- (ninguna)'),
  E'-- ══ Índices ══\n' || coalesce((select txt from s_indices), '-- (ninguno además de las llaves)'),
  E'-- ══ Funciones ══\n' || (select txt from s_funcs),
  E'-- ══ Disparadores ══\n' || coalesce((select txt from s_trig), '-- (ninguno)'),
  E'-- ══ Políticas (RLS) ══\n' || coalesce((select txt from s_pol), '-- (ninguna)'),
  E'-- ══ Permisos de las tablas ══\n' || (select txt from s_gtab),
  E'-- ══ Permisos de las secuencias ══\n' || coalesce((select txt from s_gseq), '-- (ninguna)'),
  E'-- ══ Permisos de las funciones ══\n' || (select txt from s_gfun),
  E'-- ══ Permisos por defecto (los que recibe lo que se cree después) ══\n' || coalesce((select txt from s_gdef), '-- (los de PostgreSQL)')
) as esquema
) || E'\n\n' || (
select concat_ws(E'\n\n',
  E'-- ══ Depósito de archivos ══\n' || coalesce((select string_agg(format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)%svalues (%L, %L, %s, %s, %L)%son conflict (id) do update set public = excluded.public, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;', E'\n', id, name, case when public then 'true' else 'false' end, coalesce(file_size_limit::text, 'null'), allowed_mime_types, E'\n'), E'\n' order by id collate "C") from storage.buckets), '-- (ninguno)'),
  E'-- ══ Políticas del depósito ══\n' || coalesce((select string_agg(format('drop policy if exists %I on %I.%I;', policyname, schemaname, tablename) || E'\n' ||
         format('create policy %I on %I.%I as %s for %s to %s', policyname, schemaname, tablename, lower(permissive), lower(cmd), array_to_string(roles, ', '))
         || coalesce(E'\n  using (' || qual || ')', '') || coalesce(E'\n  with check (' || with_check || ')', '') || ';', E'\n' order by tablename, policyname)
       from pg_policies where schemaname = 'storage'), '-- (ninguna)'),
  E'-- ══ Tareas programadas (pg_cron) ══\n' || coalesce((select string_agg(format('select cron.schedule(%L, %L, %L);', jobname, schedule, command), E'\n' order by jobname collate "C") from cron.job), '-- (ninguna)'),
  E'-- ══ Disparador de eventos ══\n' || coalesce((select string_agg(format('drop event trigger if exists %I;', evtname) || E'\n' || format('create event trigger %I on %s', evtname, evtevent) || coalesce(' when tag in (' || (select string_agg(quote_literal(x), ', ') from unnest(evttags) x) || ')', '') || format(' execute function %s();', evtfoid::regproc), E'\n' order by evtname) from pg_event_trigger where evtfoid::regproc::text like '%rls_auto_enable%'), '-- (ninguno)')
) as extras
)) as todo;
